function choiceOptionsField({ key, n8nKey = 'fieldOptions', label, addLabel, fieldType, optionLabel }) {
  return {
    key,
    n8nKey,
    label,
    kind: 'fixedCollection',
    value: { values: [{ option: '' }] },
    required: true,
    multiple: true,
    sortable: true,
    collectionKey: 'values',
    collectionLabel: 'Values',
    addLabel,
    showWhen: { fieldType: [fieldType] },
    ...(fieldType === 'dropdown'
      ? { description: 'List of options that can be selected from the dropdown' }
      : {}),
    fields: [
      {
        key: 'option',
        label: optionLabel,
        kind: 'text',
        sourceKind: 'string',
        value: '',
        required: false,
      },
    ],
  };
}

