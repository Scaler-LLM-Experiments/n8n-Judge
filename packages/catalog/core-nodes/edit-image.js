const capitalize = (value) => value.charAt(0).toUpperCase() + value.slice(1);

function normalizeOperationField(field) {
  const {
    operation,
    n8nKey,
    dependsOn = {},
    ...metadata
  } = field;
  const normalizedDependencies = Object.fromEntries(
    Object.entries(dependsOn).map(([key, values]) => [
      `${operation}${capitalize(key)}`,
      values,
    ]),
  );

  return {
    key: `${operation}${capitalize(n8nKey)}`,
    n8nKey,
    ...metadata,
    required: false,
    showWhen: { operation: [operation], ...normalizedDependencies },
    n8nShowWhen: { operation: [operation], ...dependsOn },
  };
}

